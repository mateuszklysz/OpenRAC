"""
Keeps port/lang/openrac.pot, the template of the port's own words, in step with the code, and
checks each translation against it (common/i18n.h, port/lang/README.md).

  i18n_template.py           writes lang/openrac.pot from the texts the code marks
  i18n_template.py --check   says what the template lacks or has too much, and checks every
                             lang/*.po: no text the template lacks, the same {} placeholders as the
                             English; the test the port's ctest runs (no disc needed)

A text is marked where it is written: tr("...") where it is shown, N_("...") in a table of
texts. Adjacent string literals are one text, as in C.
"""
import argparse
import re
import sys
from pathlib import Path

PORT = Path(__file__).resolve().parent.parent
TEMPLATE = PORT / "lang" / "openrac.pot"
SOURCES = ("common", "game/common", "platform", "renderer", "viewer", "media", "audio")
SUFFIXES = {".c", ".cpp", ".h", ".mm"}
SKIPPED = {"i18n.h", "i18n.cpp"}  # their comments show tr() and N_()

# What a translator should know of a text, by the file it is in.
VIDEO_PAGE = ("The Video options page, in the game's font: about as short as the English. Accented "
              "letters are drawn plain (ą as a).")
NOTES = {
    "game/common/options_menu.cpp": VIDEO_PAGE,
    "game/common/settings.cpp": VIDEO_PAGE,
    "platform/window.cpp": "A message box: any length, every letter is drawn.",
}

MARK = re.compile(r'\b(?:tr|N_)\(\s*((?:"(?:[^"\\\n]|\\.)*"\s*)+)\)')
LITERAL = re.compile(r'"((?:[^"\\\n]|\\.)*)"')
ESCAPES = {"n": "\n", "t": "\t", '"': '"', "\\": "\\"}


def unescape(text):
    return re.sub(r"\\(.)", lambda m: ESCAPES.get(m.group(1), m.group(1)), text)


def escape(text):
    return text.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n").replace("\t", "\\t")


def marked():
    """{text: [file, ...]}, in the order first found. No line numbers: the template changes only
    when the texts do."""
    found = {}
    for top in SOURCES:
        for path in sorted((PORT / top).rglob("*")):
            if path.suffix not in SUFFIXES or not path.is_file() or path.name in SKIPPED:
                continue
            source = path.read_text(encoding="utf-8")
            relative = path.relative_to(PORT).as_posix()
            for m in MARK.finditer(source):
                text = "".join(unescape(part) for part in LITERAL.findall(m.group(1)))
                places = found.setdefault(text, [])
                if relative not in places:
                    places.append(relative)
    return found


def quoted(keyword, text):
    """A .po string, wrapped as gettext tools wrap one: a long text continued on lines of its own."""
    line = f'{keyword} "{escape(text)}"'
    if len(line) <= 79 and "\n" not in text:
        return line + "\n"
    parts, current = [], ""
    for word in re.findall(r"\S+\s*|\s+", text):
        if current and len(escape(current + word)) > 76:
            parts.append(current)
            current = ""
        current += word
    if current:
        parts.append(current)
    return f'{keyword} ""\n' + "".join(f'"{escape(p)}"\n' for p in parts)


def template(found):
    out = [
        "# The port's own words, to translate: port/lang/README.md says how.\n",
        "# Generated by port/tools/i18n_template.py from the code; do not edit.\n",
        'msgid ""\n',
        'msgstr ""\n',
        '"Content-Type: text/plain; charset=UTF-8\\n"\n',
    ]
    for text, places in found.items():
        out.append("\n")
        notes = sorted({NOTES[f] for f in places if f in NOTES})
        out.extend(f"#. {note}\n" for note in notes)
        out.append("#: " + " ".join(places) + "\n")
        out.append(quoted("msgid", text))
        out.append('msgstr ""\n')
    return "".join(out)


def read_po(path):
    """{msgid: msgstr} of a .po file (comments and the other keywords passed over)."""
    entries, key, into = {}, None, None
    current = {"msgid": "", "msgstr": ""}

    def finish():
        if key is not None:
            entries[current["msgid"]] = current["msgstr"]

    for raw in path.read_text(encoding="utf-8").splitlines():
        line = raw.strip()
        if not line or line.startswith("#"):
            continue
        word = line.split(" ", 1)[0]
        if word == "msgid":
            finish()
            key, into = True, "msgid"
            current = {"msgid": "", "msgstr": ""}
        elif word == "msgstr":
            into = "msgstr"
        elif line.startswith('"'):
            if into is None:
                continue
        else:
            into = None
            continue
        current[into] += "".join(unescape(p) for p in LITERAL.findall(line))
    finish()
    return entries


def placeholders(text):
    return re.findall(r"\{[^{}]*\}", text)


def check(found):
    problems = []
    wanted = template(found)
    if not TEMPLATE.exists() or TEMPLATE.read_text(encoding="utf-8") != wanted:
        problems.append(f"{TEMPLATE.relative_to(PORT)} is not the code's: run port/tools/i18n_template.py")
    for po in sorted(TEMPLATE.parent.glob("*.po")):
        entries = read_po(po)
        name = po.relative_to(PORT)
        if "Language:" not in entries.get("", ""):
            problems.append(f"{name}: the header has no Language:")
        missing = 0
        for english, translated in entries.items():
            if english == "":
                continue
            if english not in found:
                problems.append(f"{name}: {english!r} is not a text of the code (gone, or changed)")
            elif translated and placeholders(translated) != placeholders(english):
                problems.append(f"{name}: {english!r}: the placeholders are {placeholders(english)}, "
                                f"the translation's {placeholders(translated)}")
        missing = sum(1 for t in found if not entries.get(t))
        if missing:
            print(f"{name}: {missing} of {len(found)} texts not translated (shown in English)")
    for p in problems:
        print(p, file=sys.stderr)
    return 1 if problems else 0


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    found = marked()
    if args.check:
        return check(found)
    TEMPLATE.parent.mkdir(exist_ok=True)
    TEMPLATE.write_text(template(found), encoding="utf-8")
    print(f"{TEMPLATE.relative_to(PORT)}: {len(found)} texts")
    return 0


if __name__ == "__main__":
    sys.exit(main())
